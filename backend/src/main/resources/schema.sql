CREATE OR REPLACE PROCEDURE atualizar_alunos_inativos()
    LANGUAGE plpgsql
    AS $$
    DECLARE
    cur_alunos CURSOR FOR
    SELECT
        co.cpf_aluno,
        u.nome AS nome_aluno,
        co.id_curso,
        c.nome AS nome_curso,
        co.data_compra,
        MAX(ass.data_assistida) AS ultima_aula_assistida
    FROM compra co
             JOIN aluno a
                  ON a.cpf_aluno = co.cpf_aluno
             JOIN usuario u
                  ON u.cpf = a.cpf_aluno
             JOIN curso c
                  ON c.id_curso = co.id_curso
             LEFT JOIN assistir ass
                       ON ass.cpf_aluno = co.cpf_aluno
                           AND ass.id_curso = co.id_curso
    GROUP BY
        co.cpf_aluno,
        u.nome,
        co.id_curso,
        c.nome,
        co.data_compra;

    v_registro RECORD;
        v_data_referencia DATE;
        v_dias_inativo INT;
        v_motivo VARCHAR(50);
    BEGIN
    OPEN cur_alunos;

    LOOP
    FETCH cur_alunos INTO v_registro;
            EXIT WHEN NOT FOUND;

            v_data_referencia := COALESCE(
                v_registro.ultima_aula_assistida,
                v_registro.data_compra
            );

            v_dias_inativo := CURRENT_DATE - v_data_referencia;

            IF v_registro.ultima_aula_assistida IS NULL THEN
                v_motivo := 'NUNCA_ASSISTIU';
    ELSE
                v_motivo := 'SEM_ACESSO_RECENTE';
    END IF;

            IF v_dias_inativo > 1 THEN

                INSERT INTO alunos_inativos (
                    cpf_aluno,
                    nome_aluno,
                    id_curso,
                    nome_curso,
                    data_compra,
                    ultima_aula_assistida,
                    data_referencia_inatividade,
                    dias_inativo,
                    motivo,
                    data_atualizacao
                )
                VALUES (
                    v_registro.cpf_aluno,
                    v_registro.nome_aluno,
                    v_registro.id_curso,
                    v_registro.nome_curso,
                    v_registro.data_compra,
                    v_registro.ultima_aula_assistida,
                    v_data_referencia,
                    v_dias_inativo,
                    v_motivo,
                    now()
                )
                ON CONFLICT (cpf_aluno, id_curso)
                DO UPDATE SET
                    nome_aluno = EXCLUDED.nome_aluno,
                    nome_curso = EXCLUDED.nome_curso,
                    data_compra = EXCLUDED.data_compra,
                    ultima_aula_assistida = EXCLUDED.ultima_aula_assistida,
                    data_referencia_inatividade = EXCLUDED.data_referencia_inatividade,
                    dias_inativo = EXCLUDED.dias_inativo,
                    motivo = EXCLUDED.motivo,
                    data_atualizacao = now();

    ELSE

    DELETE FROM alunos_inativos ai
    WHERE ai.cpf_aluno = v_registro.cpf_aluno
      AND ai.id_curso = v_registro.id_curso;

    END IF;
    END LOOP;

    CLOSE cur_alunos;
    END;
    $$;
    @@

CREATE TABLE IF NOT EXISTS log_preco_curso (
    id_log BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_curso BIGINT,
    preco_antigo DECIMAL(10,2),
    preco_novo DECIMAL(10,2),
    data_alteracao TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    usuario_banco VARCHAR(50)
);
@@

CREATE OR REPLACE FUNCTION fn_log_preco_curso()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.preco IS DISTINCT FROM NEW.preco THEN
        INSERT INTO log_preco_curso (
            id_curso,
            preco_antigo,
            preco_novo,
            usuario_banco
        )
        VALUES (
            NEW.id_curso,
            OLD.preco,
            NEW.preco,
            current_user
        );
END IF;

RETURN NEW;
END;
$$;
@@

DROP TRIGGER IF EXISTS trg_auditoria_preco_curso ON curso;
@@

CREATE TRIGGER trg_auditoria_preco_curso
AFTER UPDATE ON curso
            FOR EACH ROW
            EXECUTE FUNCTION fn_log_preco_curso();
@@

CREATE OR REPLACE FUNCTION fn_verificar_compra_antes_assistir()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM compra co
        WHERE co.id_curso = NEW.id_curso
          AND co.cpf_aluno = NEW.cpf_aluno
    ) THEN
        RAISE EXCEPTION 'O aluno % não pode assistir aulas do curso %, pois não comprou o curso.',
            NEW.cpf_aluno,
            NEW.id_curso;
END IF;

RETURN NEW;
END;
$$;
@@

DROP TRIGGER IF EXISTS trg_verificar_compra_antes_assistir ON assistir;
@@

CREATE TRIGGER trg_verificar_compra_antes_assistir
BEFORE INSERT OR UPDATE ON assistir
                       FOR EACH ROW
                       EXECUTE FUNCTION fn_verificar_compra_antes_assistir();
@@

CREATE OR REPLACE FUNCTION fn_verficar_conclusao_do_curso_liberar_certificado()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
v_total_aulas INT;
    v_aulas_assistidas INT;
BEGIN
SELECT COUNT(*)
INTO v_total_aulas
FROM aula a
WHERE a.id_curso = NEW.id_curso_concluido;

IF v_total_aulas = 0 THEN
        RAISE EXCEPTION
            'O curso em questão não possui aulas cadastradas';
END IF;

SELECT COUNT(DISTINCT (ass.id_curso, ass.id_modulo, ass.id_aula))
INTO v_aulas_assistidas
FROM assistir ass
WHERE ass.id_curso = NEW.id_curso_concluido
  AND ass.cpf_aluno = NEW.cpf_aluno_graduado;

IF v_total_aulas <> v_aulas_assistidas THEN
        RAISE EXCEPTION
        'Certificado negado: aluno não concluiu todas as aulas do curso';
END IF;

RETURN NEW;
END;
$$;
@@

DROP TRIGGER IF EXISTS trg_verficar_conclusao_do_curso_liberar_certificado ON certificado_curso;
@@

CREATE TRIGGER trg_verficar_conclusao_do_curso_liberar_certificado
    BEFORE INSERT ON certificado_curso
    FOR EACH ROW
    EXECUTE FUNCTION fn_verficar_conclusao_do_curso_liberar_certificado();
@@

