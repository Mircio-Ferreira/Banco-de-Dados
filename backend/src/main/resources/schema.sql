CREATE OR REPLACE FUNCTION calcular_desconto(
    IN preco NUMERIC,
    IN desconto NUMERIC
)
RETURNS NUMERIC
LANGUAGE plpgsql
AS $$
DECLARE
preco_com_desconto NUMERIC;
BEGIN
    IF desconto > 100 OR desconto < 0 THEN
        RAISE EXCEPTION 'O desconto deve estar entre 0 e 100%%';
END IF;

    preco_com_desconto := preco - (preco * (desconto / 100));

RETURN ROUND(preco_com_desconto, 2);
END;
$$;
@@
CREATE OR REPLACE FUNCTION calcular_carga_horaria_total(
       IN v_id_curso BIGINT
)
       RETURNS INT
       LANGUAGE plpgsql
       AS $$

       DECLARE horas_totais INT;

       BEGIN
       SELECT SUM(carga_horaria)
       INTO horas_totais
       FROM modulo
       WHERE id_curso = v_id_curso;

       RETURN COALESCE(horas_totais,0);
       END;
       $$;
@@
CREATE OR REPLACE PROCEDURE aplicar_desconto_em_categoria(
       IN in_categoria VARCHAR,
       IN desconto DOUBLE PRECISION
)
       LANGUAGE plpgsql
       AS $$

       DECLARE v_id_categoria BIGINT;

       BEGIN

       SELECT id_categoria
       INTO v_id_categoria
       FROM categoria c
       WHERE c.nome_da_categoria = in_categoria;

        IF v_id_categoria IS NULL THEN
                RAISE EXCEPTION 'Categoria "%" não encontrada.', in_categoria;
        END IF;

       UPDATE curso
       SET preco = calcular_desconto(preco, desconto::NUMERIC)
       WHERE id_curso IN (
           SELECT c.id_curso
           FROM curso c
           JOIN possui p
           ON c.id_curso = p.id_curso AND p.id_categoria = v_id_categoria
           );

       END;
       $$;
        @@
